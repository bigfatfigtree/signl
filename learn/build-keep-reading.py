#!/usr/bin/env python3
"""Adds/refreshes the "Keep reading" rail at the foot of every Learn article.

    python3 learn/build-keep-reading.py

Each article gets a marker-delimited block (<!-- KEEP-READING v1 --> ...
<!-- /KEEP-READING -->) inserted immediately before </main>, linking 3 related
articles: same topic first (city guides link to city guides), then same
audience, then newest overall. Re-running replaces the block in place.
Everything outside the block is preserved byte-for-byte (asserted per file).
See INTEGRATION.md for the daily-article flow.
"""
import glob, html, json, os, re
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
META = os.path.join(HERE, "articles-meta.json")
MARK_A = "<!-- KEEP-READING v1"
MARK_B = "<!-- /KEEP-READING -->"

CSS = """.kr-block{border-top:1px solid var(--line2)}
.kr-label{font-family:'Space Grotesk',monospace;font-size:.75rem;font-weight:700;letter-spacing:.14em;text-transform:uppercase;color:#006AFC;margin-bottom:16px}
.kr-grid{display:grid;gap:18px}
@media(min-width:760px){.kr-grid{grid-template-columns:repeat(3,1fr)}}
.kr-card{background:var(--card);border:1px solid var(--line2);border-radius:20px;overflow:hidden;text-decoration:none;color:inherit;display:flex;flex-direction:column;box-shadow:var(--sh-md)}
.kr-card img{width:100%;aspect-ratio:16/9;object-fit:cover;display:block}
.kr-card .kr-t{font-weight:800;font-size:1.02rem;line-height:1.3;padding:14px 16px 4px;letter-spacing:-.014em}
.kr-card .kr-m{font-size:.82rem;color:var(--ink3);font-weight:600;padding:0 16px 14px}"""

def esc(t):
    return html.escape(t or "", quote=True)

def fmt_date(iso):
    y, m, d = (int(x) for x in iso.split("-"))
    return date(y, m, d).strftime("%b %-d, %Y")

BLOCK_RE = re.compile(r"<!-- KEEP-READING v1.*?<!-- /KEEP-READING -->\n?", re.S)

def scan(path):
    s = BLOCK_RE.sub("", open(path, encoding="utf-8").read())
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", s, re.S)
    # Decode entities from the scanned source so esc() on output encodes exactly
    # once (bug 2026-11-08: raw "&ndash;" in an H1 was re-escaped to "&amp;ndash;"
    # and rendered literally on cards).
    title = html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", h1.group(1))).strip()) if h1 else ""
    dp = re.search(r'"datePublished":\s*"(\d{4}-\d{2}-\d{2})', s)
    band = re.search(r'class="photo-band[^"]*">\s*<img src="([^"]+)" alt="([^"]*)"', s)
    main = re.search(r"<main.*?</main>", s, re.S)
    words = len(re.sub(r"<[^>]+>", " ", re.sub(r"<script.*?</script>|<style.*?</style>", " ", main.group(0), flags=re.S)).split()) if main else 0
    return dict(title=title, date=dp.group(1) if dp else "1970-01-01",
                hero=band.group(1) if band else "../assets/og-image.png",
                hero_alt=html.unescape(band.group(2)) if band else "", read=max(1, round(words / 200)))

def main():
    meta = json.load(open(META, encoding="utf-8"))
    arts = {}
    for path in sorted(glob.glob(os.path.join(HERE, "*.html"))):
        f = os.path.basename(path)
        if f == "index.html":
            continue
        a = scan(path)
        m = meta.get(f, {})
        a.update(file=f, topic=m.get("topic"), audience=m.get("audience", "both"),
                 city=bool(m.get("cityGuide")))
        arts[f] = a
    ordered = sorted(arts.values(), key=lambda a: (a["date"], a["file"]), reverse=True)

    def related(a):
        picks = []
        def add(pool):
            for c in pool:
                if c["file"] != a["file"] and c not in picks and len(picks) < 3:
                    picks.append(c)
        if a["city"]:
            add([c for c in ordered if c["city"]])
        else:
            add([c for c in ordered if not c["city"] and c["topic"] == a["topic"]])
        add([c for c in ordered if not c["city"] and c["audience"] in (a["audience"], "both")])
        add(ordered)
        return picks[:3]

    block_re = re.compile(re.escape(MARK_A) + r".*?" + re.escape(MARK_B) + r"\n?", re.S)
    changed = 0
    for f, a in arts.items():
        path = os.path.join(HERE, f)
        s = open(path, encoding="utf-8").read()
        rel = related(a)
        cards = "\n".join(
            f'        <a class="kr-card" href="{c["file"]}"><img src="{c["hero"]}" alt="{esc(c["hero_alt"])}" loading="lazy">'
            f'<span class="kr-t">{esc(c["title"])}</span>'
            f'<span class="kr-m">{fmt_date(c["date"])} &middot; {c["read"]} min read</span></a>' for c in rel)
        block = (f'{MARK_A} (generated by build-keep-reading.py — do not hand-edit) -->\n'
                 f'  <section class="block kr-block">\n    <style>{CSS}</style>\n    <div class="wrap">\n'
                 f'      <p class="kr-label">Keep reading</p>\n      <div class="kr-grid">\n{cards}\n      </div>\n'
                 f'    </div>\n  </section>\n{MARK_B}\n')
        if MARK_A in s:
            new = block_re.sub(block, s, count=1)
        else:
            assert s.count("</main>") == 1, f"{f}: expected exactly one </main>"
            new = s.replace("</main>", block + "</main>", 1)
        # byte-safety: removing the block must restore the pre-edit file exactly
        assert block_re.sub("", new) == block_re.sub("", s), f"{f}: content outside the block changed!"
        if new != s:
            open(path, "w", encoding="utf-8").write(new)
            changed += 1
    print(f"keep-reading: {changed} article files updated, {len(arts)} total, all byte-safe outside the block")

if __name__ == "__main__":
    main()
